import AppKit
import SwiftUI

/// Settings uses the notch's own look: near-black surfaces, white type, one amber accent.
enum SettingsTheme {
    static let window = Color(red: 0.055, green: 0.055, blue: 0.063)
    static let sidebar = Color(red: 0.078, green: 0.078, blue: 0.088)
    static let card = Color(red: 0.112, green: 0.112, blue: 0.126)
    static let cardRaised = Color(red: 0.145, green: 0.145, blue: 0.16)
    static let stroke = Color.white.opacity(0.075)
    static let secondary = Color(white: 0.64)
    static let tertiary = Color(white: 0.45)
    static let accent = Palette.amber
    static let nsWindow = NSColor(red: 0.055, green: 0.055, blue: 0.063, alpha: 1)
}

enum SettingsPane: String, CaseIterable, Identifiable {
    case agents, character, sounds, shortcuts, general

    var id: String { rawValue }

    var title: String {
        switch self {
        case .agents: "Agents"
        case .character: "Character"
        case .sounds: "Sounds"
        case .shortcuts: "Shortcuts"
        case .general: "General"
        }
    }

    var icon: String {
        switch self {
        case .agents: "point.3.connected.trianglepath.dotted"
        case .character: "face.smiling"
        case .sounds: "speaker.wave.2"
        case .shortcuts: "command"
        case .general: "gearshape"
        }
    }

    /// `--settings-pane <name>` opens a specific page (handy for screenshots and docs).
    static var launchPane: SettingsPane {
        let args = CommandLine.arguments
        guard let i = args.firstIndex(of: "--settings-pane"), i + 1 < args.count else { return .agents }
        return SettingsPane(rawValue: args[i + 1]) ?? .agents
    }

    var subtitle: String {
        switch self {
        case .agents: "The AI coding tools Pip watches. Connected agents show up in the notch the moment they start working."
        case .character: "Who lives in your notch. Every style reacts to the same moods; pick the one you like looking at."
        case .sounds: "Short sounds Pip makes when something needs you. All of them are generated by Pip itself."
        case .shortcuts: "Handle requests without touching the mouse. They work from any app."
        case .general: "Startup, previews and where Pip keeps its files."
        }
    }
}

struct SettingsView: View {
    @ObservedObject var integrations: IntegrationsModel
    var runDemo: () -> Void = {}
    @State private var pane: SettingsPane = .launchPane

    var body: some View {
        HStack(spacing: 0) {
            SettingsSidebar(pane: $pane, integrations: integrations)
                .frame(width: 214)
            Rectangle().fill(SettingsTheme.stroke).frame(width: 1)
            ScrollView {
                VStack(alignment: .leading, spacing: 24) {
                    VStack(alignment: .leading, spacing: 6) {
                        Text(pane.title)
                            .font(.system(size: 26, weight: .bold))
                        Text(pane.subtitle)
                            .font(.system(size: 13))
                            .foregroundStyle(SettingsTheme.secondary)
                            .fixedSize(horizontal: false, vertical: true)
                    }
                    content
                }
                .padding(.horizontal, 32)
                .padding(.top, 44)
                .padding(.bottom, 32)
                .frame(maxWidth: .infinity, alignment: .leading)
            }
            .scrollIndicators(.never)
            .id(pane)
        }
        .frame(width: 840, height: 620)
        .background(SettingsTheme.window)
        .foregroundStyle(.white)
        .tint(SettingsTheme.accent)
        .environment(\.colorScheme, .dark)
        .onAppear { integrations.connectDetected() }
    }

    @ViewBuilder
    private var content: some View {
        switch pane {
        case .agents: AgentsPane(model: integrations)
        case .character: CharacterPane()
        case .sounds: SoundsPane()
        case .shortcuts: ShortcutsPane()
        case .general: GeneralPane(model: integrations, runDemo: runDemo)
        }
    }
}

// MARK: Sidebar

private struct SettingsSidebar: View {
    @Binding var pane: SettingsPane
    @ObservedObject var integrations: IntegrationsModel

    var body: some View {
        VStack(alignment: .leading, spacing: 0) {
            HStack(spacing: 11) {
                NotchMark()
                VStack(alignment: .leading, spacing: 1) {
                    Text("Pip").font(.system(size: 16, weight: .bold))
                    Text("Agent companion")
                        .font(.system(size: 11))
                        .foregroundStyle(SettingsTheme.secondary)
                }
            }
            .padding(.horizontal, 18)
            .padding(.top, 50)
            .padding(.bottom, 24)

            VStack(spacing: 2) {
                ForEach(SettingsPane.allCases) { item in
                    SidebarItem(
                        pane: item,
                        selected: item == pane,
                        count: item == .agents ? integrations.connected.count : nil
                    ) { pane = item }
                }
            }
            .padding(.horizontal, 10)

            Spacer()

            HStack(spacing: 8) {
                Circle()
                    .fill(integrations.connected.isEmpty ? SettingsTheme.tertiary : Palette.green)
                    .frame(width: 7, height: 7)
                Text(statusText)
                    .font(.system(size: 11.5))
                    .foregroundStyle(SettingsTheme.secondary)
            }
            .padding(18)
        }
        .frame(maxHeight: .infinity, alignment: .top)
        .background(SettingsTheme.sidebar)
    }

    private var statusText: String {
        let count = integrations.connected.count
        return count == 0 ? "No agents connected" : "Watching \(count) agent\(count == 1 ? "" : "s")"
    }
}

/// The app mark: a tiny living notch with eyes.
private struct NotchMark: View {
    var body: some View {
        ZStack(alignment: .top) {
            NotchShape(topRadius: 3, bottomRadius: 8)
                .fill(Color.black)
            NotchShape(topRadius: 3, bottomRadius: 8)
                .stroke(Color.white.opacity(0.14), lineWidth: 1)
            CharacterView(mood: .idle, style: .livingNotch)
                .frame(width: 34, height: 18)
                .padding(.top, 2)
        }
        .frame(width: 40, height: 24)
        .accessibilityHidden(true)
    }
}

private struct SidebarItem: View {
    let pane: SettingsPane
    let selected: Bool
    let count: Int?
    let action: () -> Void
    @State private var hovering = false

    var body: some View {
        Button(action: action) {
            HStack(spacing: 10) {
                Image(systemName: pane.icon)
                    .font(.system(size: 13, weight: .medium))
                    .foregroundStyle(selected ? SettingsTheme.accent : SettingsTheme.secondary)
                    .frame(width: 20)
                Text(pane.title)
                    .font(.system(size: 13, weight: selected ? .semibold : .regular))
                    .foregroundStyle(selected ? Color.white : Color.white.opacity(0.82))
                Spacer()
                if let count, count > 0 {
                    Text("\(count)")
                        .font(.system(size: 10.5, weight: .semibold, design: .rounded))
                        .foregroundStyle(SettingsTheme.secondary)
                        .padding(.horizontal, 6)
                        .padding(.vertical, 1)
                        .background(Capsule().fill(Color.white.opacity(0.08)))
                }
            }
            .padding(.horizontal, 10)
            .frame(height: 34)
            .background(
                RoundedRectangle(cornerRadius: 9, style: .continuous)
                    .fill(Color.white.opacity(selected ? 0.085 : hovering ? 0.04 : 0))
            )
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .onHover { hovering = $0 }
        .accessibilityAddTraits(selected ? .isSelected : [])
    }
}

// MARK: Window

@MainActor
final class SettingsWindowController {
    private var window: NSWindow?
    private let integrations: IntegrationsModel
    private let runDemo: () -> Void

    init(integrations: IntegrationsModel, runDemo: @escaping () -> Void) {
        self.integrations = integrations
        self.runDemo = runDemo
    }

    /// Opens Settings, centred on `screen` (the notch's screen when opened from the notch).
    func show(on screen: NSScreen? = nil) {
        if window == nil {
            let host = NSHostingController(rootView: SettingsView(integrations: integrations, runDemo: runDemo))
            let window = NSWindow(contentViewController: host)
            window.title = "Pip Settings"
            window.styleMask = [.titled, .closable, .miniaturizable, .fullSizeContentView]
            window.titlebarAppearsTransparent = true
            window.titleVisibility = .hidden
            window.isMovableByWindowBackground = true
            window.appearance = NSAppearance(named: .darkAqua)
            window.backgroundColor = SettingsTheme.nsWindow
            window.isReleasedWhenClosed = false
            window.setContentSize(NSSize(width: 840, height: 620))
            self.window = window
        }
        if let window, !window.isVisible || screen != nil { place(window, on: screen) }
        integrations.refresh()
        Log.ui.notice("Settings window shown")
        NSApp.activate()
        window?.makeKeyAndOrderFront(nil)
        // Activation can be refused while another app is frontmost; the window still comes forward.
        window?.orderFrontRegardless()
    }

    /// Centres the window on the screen under the pointer: the one with the notch you just clicked,
    /// not necessarily the main display.
    private func place(_ window: NSWindow, on preferred: NSScreen?) {
        let pointer = NSEvent.mouseLocation
        let underPointer = NSScreen.screens.first { $0.frame.insetBy(dx: -2, dy: -2).contains(pointer) }
        guard let screen = preferred ?? underPointer ?? NSScreen.main else { return }
        let area = screen.visibleFrame
        var frame = window.frame
        frame.size.height = min(frame.height, area.height - 40)
        frame.origin = CGPoint(x: area.midX - frame.width / 2, y: area.midY - frame.height / 2)
        window.setFrame(frame, display: false)
    }
}
